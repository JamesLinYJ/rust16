//! BIOS boot records. Relocate to 0000:0600 before loading the next stage.
use crate::machine::Segment;

pub fn record(mbr: bool) -> Result<Vec<u8>, String> {
    record_at(mbr, 0x300)
}

pub fn record_at(mbr: bool, loader: u16) -> Result<Vec<u8>, String> {
    let mut s = Segment::default();
    s.emit(&[0xeb, 88, 0x90]);
    s.bytes.resize(90, 0);
    // Normalize CS and DS, establish a stack, copy 7C00h to 0600h.
    s.emit(&[
        0xfa, 0x31, 0xc0, 0x8e, 0xd0, 0xbc, 0xf0, 0x2f, 0x8e, 0xd8, 0x8e, 0xc0, 0xfc, 0xbe, 0,
        0x7c, 0xbf, 0, 6, 0xb9, 0, 1, 0xf3, 0xa5, 0xea,
    ]);
    s.word(0x600 + s.bytes.len() as u16 + 4);
    s.word(0);
    // DS:0800 = 16-byte EDD packet, 0810 = drive, 0812 = sectors remaining.
    s.emit(&[
        0xfb, 0x88, 0x16, 0x10, 8, 0xbf, 0, 8, 0xb9, 8, 0, 0x31, 0xc0, 0xf3, 0xab, 0xc6, 0x06, 0,
        8, 16, 0xc6, 0x06, 2, 8, 1,
    ]);
    if !mbr && loader < 0x300 {
        // The contiguous IO.SYS read may span the original VBR stack at 0000:2ff0.
        s.emit(&[0xfa, 0xb8, 0, 0x20, 0x8e, 0xd0, 0xbc, 0xf0, 0xff, 0xfb]);
    }
    if mbr {
        s.emit(&[0xbe, 0xbe, 7, 0xb9, 4, 0]);
        s.label("part");
        s.emit(&[0x80, 0x3c, 0x80]);
        s.branch(0x74, "active");
        s.emit(&[0x83, 0xc6, 16, 0x49]);
        s.branch(0x75, "part");
        s.relative(0xe9, "fail");
        s.label("active");
        s.emit(&[
            0x83, 0xc6, 8, 0xbf, 8, 8, 0xa5, 0xa5, 0xb8, 0xc0, 7, 0xb9, 1, 0,
        ]);
    } else {
        // The formatter writes IO.SYS's first absolute sector and sector count.
        s.emit(&[
            0xbe,
            0xa0,
            7,
            0xbf,
            8,
            8,
            0xa5,
            0xa5,
            0xad,
            0x89,
            0xc1,
            0xb8,
            loader as u8,
            (loader >> 8) as u8,
        ]);
    }
    s.emit(&[0xa3, 6, 8, 0x89, 0x0e, 0x12, 8, 0x09, 0xc9]);
    s.branch(0x74, "fail");
    s.emit(&[0x80, 0xfa, 0x80]);
    s.branch(0x72, "geometry");
    s.emit(&[0xbb, 0xaa, 0x55, 0xb4, 0x41, 0xcd, 0x13]);
    s.branch(0x72, "geometry");
    s.emit(&[0x81, 0xfb, 0x55, 0xaa]);
    s.branch(0x75, "geometry");
    s.emit(&[0xf6, 0xc1, 1]);
    s.branch(0x74, "geometry");
    s.label("edd");
    s.emit(&[0xbe, 0, 8, 0x8a, 0x16, 0x10, 8, 0xb4, 0x42, 0xcd, 0x13]);
    s.branch(0x72, "fail");
    s.relative(0xe9, "advance");
    s.label("geometry");
    s.emit(&[0x8a, 0x16, 0x10, 8, 0xb4, 8, 0xcd, 0x13]);
    s.branch(0x72, "fail");
    s.emit(&[
        0x83, 0xe1, 63, 0x89, 0x0e, 0x14, 8, 0x31, 0xc0, 0x88, 0xf0, 0x40, 0xf7, 0xe1, 0xa3, 0x16,
        8,
    ]);
    s.label("chs");
    s.emit(&[0xa1, 8, 8, 0x8b, 0x16, 10, 8, 0x3b, 0x16, 0x16, 8]);
    s.branch(0x73, "fail");
    s.emit(&[0xf7, 0x36, 0x16, 8, 0x3d, 0xff, 3]);
    s.branch(0x77, "fail");
    s.emit(&[
        0x89, 0xc7, 0x89, 0xd0, 0x31, 0xd2, 0xf7, 0x36, 0x14, 8, 0x42, 0x89, 0xd1, 0x88, 0xc6,
        0x89, 0xf8, 0x88, 0xc5, 0xd0, 0xcc, 0xd0, 0xcc, 0x08, 0xe1, 0x8a, 0x16, 0x10, 8, 0x8e,
        0x06, 6, 8, 0x31, 0xdb, 0xb8, 1, 2, 0xcd, 0x13,
    ]);
    s.branch(0x72, "fail");
    s.label("advance");
    s.emit(&[
        0x83, 0x06, 8, 8, 1, 0x83, 0x16, 10, 8, 0, 0x83, 0x06, 6, 8, 32, 0xff, 0x0e, 0x12, 8,
    ]);
    s.branch(0x74, "launch");
    s.emit(&[0x83, 0x3e, 0x14, 8, 0]);
    s.branch(0x75, "chs");
    s.relative(0xe9, "edd");
    s.label("launch");
    s.emit(&[0x8a, 0x16, 0x10, 8, 0xea]);
    s.word(if mbr { 0x7c00 } else { 0 });
    s.word(if mbr { 0 } else { loader });
    s.label("fail");
    s.emit(&[0xcd, 0x18, 0xeb, 0xfe]);
    let mut bytes = s.resolve()?;
    if bytes.len() > 416 {
        return Err(format!(
            "boot code overlaps extent at 416 ({})",
            bytes.len()
        ));
    }
    bytes.resize(510, 0);
    bytes.extend_from_slice(&[0x55, 0xaa]);
    Ok(bytes)
}
