//! Intern read-only literal bytes in the common near-data segment. All linked
//! modules share the pool, including modules compiled in separate invocations.
use crate::machine::Segment;

pub fn init(s: &mut Segment) {
    s.emit(&[0xc7, 0x06, 0, 5, 2, 5]);
}
pub fn emit(s: &mut Segment) {
    s.public("rust16_literal");
    s.emit(&[
        0x55, 0x89, 0xe5, 0x1e, 0x1e, 0x07, 0x8b, 0x1e, 0, 5, 0xbf, 2, 5, 0x8e, 0x5e, 10,
    ]);
    s.label("intern/scan");
    s.emit(&[0x39, 0xdf]);
    s.branch(0x73, "intern/new");
    s.emit(&[
        0x26, 0x8b, 0x0d, 0x47, 0x47, 0x89, 0xf8, 0x01, 0xcf, 0x3b, 0x4e, 6,
    ]);
    s.branch(0x75, "intern/scan");
    s.emit(&[0x57, 0x89, 0xc7, 0x8b, 0x76, 8, 0xf3, 0xa6, 0x5f]);
    s.branch(0x75, "intern/scan");
    s.relative(0xe9, "intern/done");
    s.label("intern/new");
    s.emit(&[0x8b, 0x4e, 6, 0x89, 0xf8, 0x01, 0xc8]);
    s.branch(0x72, "intern/full");
    s.emit(&[0x3d, 0xfe, 0x0f]);
    s.branch(0x77, "intern/full");
    s.emit(&[
        0x26, 0x89, 0x0d, 0x47, 0x47, 0x89, 0xf8, 0x8b, 0x76, 8, 0xf3, 0xa4, 0x26, 0x89, 0x3e, 0, 5,
    ]);
    s.label("intern/done");
    s.emit(&[0x8b, 0x56, 6, 0x1f, 0x5d, 0xcb]);
    s.label("intern/full");
    s.far_call("rust16_abort");
}
