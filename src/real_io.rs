//! Real-mode I/O shared by the kernel and native disk utilities.
use crate::{firmware::function, machine::Segment};
pub fn emit(s: &mut Segment) {
    crate::bios_disk::emit(s);
    // BIOS read-only range probe. Arguments: (first LBA, sector count, drive).
    // Use the caller-independent, 64 KiB aligned physical buffer at 2000:0000.
    // Checking the full proposed extent also detects data without a partition table.
    s.public("blank_edd");
    s.emit(&[
        0x55, 0x89, 0xe5, 0x31, 0xc0, 0x50, 0x50, 0xff, 0x76, 12, 0xff, 0x76, 10, 0xb8, 0, 0x20,
        0x50, 0x31, 0xc0, 0x50, 0xff, 0x76, 8, 0xb8, 16, 0, 0x50, 0x89, 0xe6, 0x8b, 0x56, 6, 0xb4,
        0x42, 0xcd, 0x13,
    ]);
    s.branch(0x72, "blank/fail");
    s.emit(&[
        0x8b, 0x4e, 8, 0x86, 0xcd, 0xb8, 0, 0x20, 0x8e, 0xc0, 0x31, 0xff, 0x31, 0xc0, 0xfc, 0xf3,
        0xaf,
    ]);
    s.branch(0x75, "blank/data");
    s.emit(&[0xb8, 1, 0]);
    s.relative(0xe9, "blank/done");
    s.label("blank/fail");
    s.emit(&[0xb8, 2, 0]);
    s.relative(0xe9, "blank/done");
    s.label("blank/data");
    s.emit(&[0x31, 0xc0]);
    s.label("blank/done");
    s.emit(&[0x89, 0xec, 0x5d, 0xcb]);
    // The DOS runtime locates its 16 KiB stack and near data in SS. The rest
    // of the PSP allocation belongs to this process and is available for the document.
    function(s, "edit_heap", &[0x8c, 0xd0, 0x05, 0, 4]);
    function(
        s,
        "edit_far_io",
        &[
            0x8b, 0x5e, 14, 0x8b, 0x56, 10, 0x8b, 0x4e, 8, 0x8b, 0x46, 6, 0x1e, 0x8e, 0x5e, 12,
            0xcd, 0x21, 0x1f, 0x73, 3, 0x0d, 0, 0x80,
        ],
    );
    // DOS reports errors via carry. Return the DOS error with bit 15 set.
    function(
        s,
        "edit_open",
        &[
            0x8b, 0x56, 8, 0x8b, 0x46, 6, 0x31, 0xc9, 0xcd, 0x21, 0x73, 3, 0x0d, 0, 0x80,
        ],
    );
    function(
        s,
        "edit_io",
        &[
            0x8b, 0x5e, 12, 0x8b, 0x56, 10, 0x8b, 0x4e, 8, 0x8b, 0x46, 6, 0xcd, 0x21, 0x73, 3,
            0x0d, 0, 0x80,
        ],
    );
    // Full BIOS keyboard result for focus navigation; DOS AH=08 keeps its byte ABI.
    function(s, "bios_scan", &[0x31, 0xc0, 0xcd, 0x16]);
    function(
        s,
        "zero_sector",
        &[
            0x8e, 0x46, 6, 0x31, 0xff, 0xb9, 0, 1, 0x31, 0xc0, 0xfc, 0xf3, 0xaf, 0x75, 1, 0x40,
        ],
    );
    function(
        s,
        "floppy_read",
        &[
            0x8b, 0x46, 8, 0x8e, 0xc0, 0x31, 0xdb, 0x8b, 0x4e, 12, 0x8a, 0x76, 10, 0x8a, 0x56, 6,
            0xb8, 1, 2, 0xcd, 0x13, 0x19, 0xc0,
        ],
    );
    function(s, "floppy_reset", &[0x31, 0xc0, 0x8b, 0x56, 6, 0xcd, 0x13]);
    function(
        s,
        "far_copy",
        &[
            0x1e, 0x8e, 0x5e, 14, 0x8b, 0x76, 12, 0x8e, 0x46, 10, 0x8b, 0x7e, 8, 0x8b, 0x4e, 6,
            0xfc, 0xf3, 0xa4, 0x1f,
        ],
    );
    function(
        s,
        "video_bios",
        &[
            0x8b, 0x46, 12, 0x8b, 0x5e, 10, 0x8b, 0x4e, 8, 0x8b, 0x56, 6, 0x55, 0xcd, 0x10, 0x5d,
        ],
    );
    function(s, "dos_key", &[0xb4, 8, 0xcd, 0x21, 0x30, 0xe4]);
    function(s, "dos_drive", &[0xb4, 0x19, 0xcd, 0x21, 0x30, 0xe4]);
    function(
        s,
        "dos_ui",
        &[
            0x8b, 0x5e, 10, 0x8b, 0x4e, 8, 0x8b, 0x56, 6, 0xb8, 2, 0xf1, 0xcd, 0x21,
        ],
    );
    function(
        s,
        "dos_line",
        &[0x8b, 0x56, 8, 0x8b, 0x4e, 6, 0xb8, 0, 0xf1, 0xcd, 0x21],
    );
    function(s, "read_port", &[0x8b, 0x56, 6, 0x31, 0xc0, 0xec]);
    function(s, "write_port", &[0x8b, 0x56, 8, 0x8b, 0x46, 6, 0xee]);
    function(s, "write_word_port", &[0x8b, 0x56, 8, 0x8b, 0x46, 6, 0xef]);
    function(
        s,
        "read_words_port",
        &[
            0x8b, 0x56, 12, 0x8e, 0x46, 10, 0x8b, 0x7e, 8, 0x8b, 0x4e, 6, 0xfc, 0xf3, 0x6d,
        ],
    );
    function(
        s,
        "video_detect",
        &[
            0xb8, 0, 0x1a, 0xcd, 0x10, 0x3c, 0x1a, 0x75, 4, 0x89, 0xd8, 0xeb, 0x13, 0xbb, 0x10, 0,
            0xb8, 0, 0x12, 0xcd, 0x10, 0x80, 0xfb, 0x10, 0xb8, 4, 0, 0x75, 3, 0xb8, 2, 0, 0x30,
            0xe4,
        ],
    );
    function(
        s,
        "serial_char",
        &[
            0x8b, 0x46, 6, 0x50, 0xba, 0xfd, 3, 0xb9, 0xff, 0xff, 0xec, 0xa8, 32, 0xe1, 0xfb, 0x58,
            0xba, 0xf8, 3, 0xee,
        ],
    );
    s.public("disk_size");
    s.emit(&[
        0x55, 0x89, 0xe5, 0x83, 0xec, 30, 0x89, 0xe6, 0xc7, 4, 30, 0, 0xb4, 0x48, 0x8b, 0x56, 6,
        0xcd, 0x13,
    ]);
    s.branch(0x72, "size/chs");
    s.emit(&[
        0x8b, 0x44, 16, 0x8b, 0x54, 18, 0x8b, 0x5c, 20, 0x0b, 0x5c, 22,
    ]);
    s.branch(0x75, "size/error");
    s.relative(0xe9, "size/out");
    s.label("size/chs");
    s.emit(&[0xb4, 8, 0x8b, 0x56, 6, 0xcd, 0x13]);
    s.branch(0x72, "size/error");
    s.emit(&[
        0x88, 0xc8, 0x24, 0xc0, 0xd0, 0xc0, 0xd0, 0xc0, 0x88, 0xc4, 0x88, 0xe8, 0x40, 0x31, 0xdb,
        0x88, 0xf3, 0x43, 0x83, 0xe1, 63, 0x93, 0xf7, 0xe1, 0xf7, 0xe3,
    ]);
    s.relative(0xe9, "size/out");
    s.label("size/error");
    s.emit(&[0x31, 0xc0, 0x99]);
    s.label("size/out");
    s.emit(&[0x89, 0xec, 0x5d, 0xcb]);
}
