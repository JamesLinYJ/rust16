//! Real-mode multiplex entry. DOS owns only its Windows broadcasts and DOSMGR;
//! the remaining functions go directly to the previous INT 2Fh handler.
use crate::machine::Segment;

pub fn emit(s: &mut Segment, kernel_data: u16) {
    // This module is linked at offset zero in the firmware OMF segment.
    let previous = s.bytes.len() as u16;
    s.emit(&[0, 0, 0, 0]);
    let empty = s.bytes.len() as u16;
    s.emit(&[0xcf]);
    let handler = s.bytes.len() as u16;
    for ax in [0x1605u16, 0x1606, 0x1607] {
        s.emit(&[0x3d]);
        s.word(ax);
        s.branch(0x74, "mux/save");
    }
    s.label("mux/chain");
    s.emit(&[0x2e, 0xff, 0x2e]);
    s.word(previous);
    s.label("mux/save");
    // Same register layout as the DOS syscall frame, followed by IP/CS/FLAGS.
    s.emit(&[
        0x1e, 0x06, 0x55, 0x57, 0x56, 0x52, 0x51, 0x53, 0x50, 0x8c, 0xd2, 0x89, 0xe3, 0xb8,
    ]);
    s.word(kernel_data);
    s.emit(&[
        0xfa, 0x8e, 0xd8, 0x8e, 0xd0, 0xbc, 0xf0, 0x2f, 0x52, 0x53, 0x52, 0x53, 0xfc,
    ]);
    s.far_call("dos16_mux");
    s.emit(&[
        0x83, 0xc4, 4, 0x5b, 0x5a, 0x8e, 0xd2, 0x89, 0xdc, 0x09, 0xc0, 0x58, 0x5b, 0x59, 0x5a,
        0x5e, 0x5f, 0x5d, 0x07, 0x1f,
    ]);
    s.branch(0x74, "mux/chain");
    s.emit(&[0xcf]);

    s.public("dos16_bind_mux");
    s.emit(&[
        0x9c, 0xfa, 0x06, 0x31, 0xc0, 0x8e, 0xc0, 0x26, 0xa1, 0xbc, 0, 0x26, 0x8b, 0x16, 0xbe, 0,
        0x89, 0xc1, 0x09, 0xd1,
    ]);
    s.branch(0x75, "mux/vector");
    s.emit(&[0xb8]);
    s.word(empty);
    s.emit(&[0x8c, 0xca]);
    s.label("mux/vector");
    s.emit(&[0x2e, 0xa3]);
    s.word(previous);
    s.emit(&[0x2e, 0x89, 0x16]);
    s.word(previous + 2);
    s.emit(&[0x26, 0xc7, 0x06, 0xbc, 0]);
    s.word(handler);
    s.emit(&[0x26, 0x8c, 0x0e, 0xbe, 0, 0x07, 0x9d, 0xcb]);
}
