//! INT 13h sector transport for the first hard disk. The low and high
//! halves of the LBA are separate stack words on every supported CPU.
use crate::machine::Segment;

pub fn emit(s: &mut Segment) {
    s.public("bios_hd");
    s.emit(&[
        0x55, 0x89, 0xe5, 0xff, 0x76, 12, 0xff, 0x76, 10, 0xff, 0x76, 8, 0xff, 0x76, 6, 0xb8, 0x80,
        0, 0x50,
    ]);
    s.far_call("bios_hd_unit");
    s.emit(&[0x89, 0xec, 0x5d, 0xcb]);
    s.public("bios_hd_unit");
    s.emit(&[
        0x55, 0x89, 0xe5, 0x8b, 0x56, 6, 0xbb, 0xaa, 0x55, 0xb4, 0x41, 0xcd, 0x13,
    ]);
    s.branch(0x72, "hd/chs");
    s.emit(&[0x81, 0xfb, 0x55, 0xaa]);
    s.branch(0x75, "hd/chs");
    s.emit(&[0xf7, 0xc1, 1, 0]);
    s.branch(0x74, "hd/chs");
    // DAP lives on SS:SP (DS=SS). Count=1 sector, offset=0.
    s.emit(&[
        0x31, 0xc0, 0x50, 0x50, 0xff, 0x76, 14, 0xff, 0x76, 12, 0xff, 0x76, 10, 0x50, 0x40, 0x50,
        0xb8, 16, 0, 0x50, 0x89, 0xe6, 0x8b, 0x46, 8, 0x05, 0x42, 0, 0x88, 0xc4, 0x30, 0xc0, 0x8b,
        0x56, 6, 0xcd, 0x13,
    ]);
    s.relative(0xe9, "hd/result");
    s.label("hd/chs");
    s.emit(&[0x8b, 0x56, 6, 0xb4, 8, 0xcd, 0x13]);
    s.branch(0x72, "hd/error");
    s.emit(&[0x31, 0xc0, 0x88, 0xf0, 0x40, 0x83, 0xe1, 63]);
    s.branch(0x74, "hd/error");
    s.emit(&[
        0x89, 0xce, 0xf7, 0xe1, 0x89, 0xc3, 0x8b, 0x56, 14, 0x39, 0xda,
    ]);
    s.branch(0x73, "hd/error");
    s.emit(&[0x8b, 0x46, 12, 0xf7, 0xf3, 0x3d, 0xff, 3]);
    s.branch(0x77, "hd/error");
    s.emit(&[
        0x89, 0xc7, 0x89, 0xd0, 0x31, 0xd2, 0xf7, 0xf6, 0x42, 0x89, 0xd1, 0x88, 0xc6, 0x89, 0xf8,
        0x88, 0xc5, 0xd0, 0xcc, 0xd0, 0xcc, 0x08, 0xe1, 0x8a, 0x56, 6, 0x31, 0xdb, 0x8e, 0x46, 10,
        0x8b, 0x46, 8, 0x04, 2, 0x88, 0xc4, 0xb0, 1, 0xcd, 0x13,
    ]);
    s.label("hd/result");
    s.emit(&[0x19, 0xc0, 0x89, 0xec, 0x5d, 0xcb]);
    s.label("hd/error");
    s.emit(&[0xb8, 0xff, 0xff, 0x89, 0xec, 0x5d, 0xcb]);
}
