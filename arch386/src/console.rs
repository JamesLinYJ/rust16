//! Install the BIOS console as a callable 8086 DOS device, including clients
//! that reach its strategy/interrupt routines through the List of Lists.
use super::{CodeAssembler, Result};
use iced_x86::code_asm::*;

pub(super) fn adapter(s: &mut rust16::machine::Segment) -> Result<()> {
    let mut driver = vec![0; 0x28];
    driver[0..4].copy_from_slice(&u32::MAX.to_le_bytes());
    driver[4..6].copy_from_slice(&0x8013u16.to_le_bytes());
    driver[6..8].copy_from_slice(&0x18u16.to_le_bytes());
    driver[8..10].copy_from_slice(&0x28u16.to_le_bytes());
    driver[10..18].copy_from_slice(b"CON     ");
    let mut a = CodeAssembler::new(16)?;
    a.mov(word_ptr(0x14).cs(), bx)?;
    a.mov(word_ptr(0x16).cs(), es)?;
    a.retf()?;
    let strategy = a.assemble(0x18)?;
    driver[0x18..0x18 + strategy.len()].copy_from_slice(&strategy);
    let mut a = CodeAssembler::new(16)?;
    let mut read = a.create_label();
    let mut write = a.create_label();
    let mut ready = a.create_label();
    let mut send = a.create_label();
    let mut done = a.create_label();
    a.pushf()?;
    a.push(ax)?;
    a.push(bx)?;
    a.push(cx)?;
    a.push(si)?;
    a.push(di)?;
    a.push(ds)?;
    a.push(es)?;
    a.cld()?;
    a.les(bx, dword_ptr(0x14).cs())?;
    a.mov(word_ptr(bx + 3).es(), 0x100)?;
    a.mov(al, byte_ptr(bx + 2).es())?;
    a.cmp(al, 4)?;
    a.je(read)?;
    a.cmp(al, 8)?;
    a.je(write)?;
    a.cmp(al, 9)?;
    a.je(write)?;
    a.cmp(al, 6)?;
    a.je(ready)?;
    a.cmp(al, 10)?;
    a.je(done)?;
    a.cmp(al, 13)?;
    a.je(done)?;
    a.cmp(al, 14)?;
    a.je(done)?;
    a.mov(word_ptr(bx + 3).es(), 0x8103)?;
    a.jmp(done)?;
    a.set_label(&mut ready)?;
    a.mov(ah, 1)?;
    a.int(0x16)?;
    a.jne(done)?;
    a.or(word_ptr(bx + 3).es(), 0x200)?;
    a.jmp(done)?;
    a.set_label(&mut read)?;
    a.cmp(word_ptr(bx + 18).es(), 0)?;
    a.je(done)?;
    a.mov(word_ptr(bx + 18).es(), 1)?;
    a.les(di, dword_ptr(bx + 14).es())?;
    a.xor(ah, ah)?;
    a.int(0x16)?;
    a.stosb()?;
    a.jmp(done)?;
    a.set_label(&mut write)?;
    a.mov(cx, word_ptr(bx + 18).es())?;
    a.jcxz(done)?;
    a.lds(si, dword_ptr(bx + 14).es())?;
    a.mov(bx, 7)?;
    a.set_label(&mut send)?;
    a.lodsb()?;
    a.mov(ah, 0x0e)?;
    a.int(0x10)?;
    a.loop_(send)?;
    a.set_label(&mut done)?;
    a.pop(es)?;
    a.pop(ds)?;
    a.pop(di)?;
    a.pop(si)?;
    a.pop(cx)?;
    a.pop(bx)?;
    a.pop(ax)?;
    a.popf()?;
    a.retf()?;
    driver.extend_from_slice(&a.assemble(0x28)?);

    let mut a = CodeAssembler::new(16)?;
    let mut copy = a.create_label();
    a.pushf()?;
    a.push(ds)?;
    a.push(es)?;
    a.push(si)?;
    a.push(di)?;
    a.push(cx)?;
    a.call(copy)?;
    a.db(&driver)?;
    a.set_label(&mut copy)?;
    a.pop(si)?;
    a.push(cs)?;
    a.pop(ds)?;
    a.mov(ax, 0x36b0)?;
    a.mov(es, ax)?;
    a.xor(di, di)?;
    a.mov(cx, driver.len() as i32)?;
    a.cld()?;
    a.rep().movsb()?;
    a.pop(cx)?;
    a.pop(di)?;
    a.pop(si)?;
    a.pop(es)?;
    a.pop(ds)?;
    a.popf()?;
    a.retf()?;
    s.public("bind_console");
    s.emit(&a.assemble(0)?);
    Ok(())
}
