//! Flat DOS test driver with ordinary, IOCTL, ready and busy requests.
use iced_x86::code_asm::*;
use std::{env, fs};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let path = env::args_os().nth(1).ok_or("expected output SYS path")?;
    let mut data = vec![0; 512];
    data[..4].copy_from_slice(&u32::MAX.to_le_bytes());
    data[4..6].copy_from_slice(&0xc800u16.to_le_bytes());
    data[6..8].copy_from_slice(&0x24u16.to_le_bytes());
    data[8..10].copy_from_slice(&0x40u16.to_le_bytes());
    data[10..18].copy_from_slice(b"ECHOBOX ");
    let mut a = CodeAssembler::new(16)?;
    a.mov(word_ptr(0x18).cs(), bx)?;
    a.mov(word_ptr(0x1a).cs(), es)?;
    a.retf()?;
    let code = a.assemble(0x24)?;
    data[0x24..0x24 + code.len()].copy_from_slice(&code);
    let mut a = CodeAssembler::new(16)?;
    let mut init = a.create_label();
    let mut open = a.create_label();
    let mut close = a.create_label();
    let mut read = a.create_label();
    let mut write = a.create_label();
    let mut busy = a.create_label();
    let mut done = a.create_label();
    let mut error = a.create_label();
    a.les(bx, dword_ptr(0x18).cs())?;
    a.mov(word_ptr(bx + 3).es(), 0x100)?;
    a.mov(al, byte_ptr(bx + 2).es())?;
    a.test(al, al)?;
    a.je(init)?;
    a.cmp(al, 13)?;
    a.je(open)?;
    a.cmp(byte_ptr(0x1c).cs(), 0)?;
    a.je(error)?;
    a.cmp(al, 14)?;
    a.je(close)?;
    a.cmp(al, 6)?;
    a.je(busy)?;
    a.cmp(al, 10)?;
    a.je(done)?;
    a.cmp(word_ptr(bx + 18).es(), 0)?;
    a.je(done)?;
    a.mov(word_ptr(bx + 18).es(), 1)?;
    a.cmp(al, 3)?;
    a.je(read)?;
    a.cmp(al, 4)?;
    a.je(read)?;
    a.cmp(al, 8)?;
    a.je(write)?;
    a.cmp(al, 12)?;
    a.je(write)?;
    a.set_label(&mut error)?;
    a.mov(word_ptr(bx + 3).es(), 0x8103)?;
    a.jmp(done)?;
    a.set_label(&mut init)?;
    a.mov(word_ptr(bx + 14).es(), 512)?;
    a.mov(word_ptr(bx + 16).es(), cs)?;
    a.jmp(done)?;
    a.set_label(&mut open)?;
    a.inc(byte_ptr(0x1c).cs())?;
    a.jmp(done)?;
    a.set_label(&mut close)?;
    a.dec(byte_ptr(0x1c).cs())?;
    a.jmp(done)?;
    a.set_label(&mut busy)?;
    a.or(word_ptr(bx + 3).es(), 0x200)?;
    a.jmp(done)?;
    a.set_label(&mut read)?;
    a.les(di, dword_ptr(bx + 14).es())?;
    a.mov(al, byte_ptr(0x1d).cs())?;
    a.mov(byte_ptr(di).es(), al)?;
    a.jmp(done)?;
    a.set_label(&mut write)?;
    a.les(di, dword_ptr(bx + 14).es())?;
    a.mov(al, byte_ptr(di).es())?;
    a.mov(byte_ptr(0x1d).cs(), al)?;
    a.set_label(&mut done)?;
    a.retf()?;
    let code = a.assemble(0x40)?;
    data[0x40..0x40 + code.len()].copy_from_slice(&code);
    fs::write(path, data)?;
    Ok(())
}
